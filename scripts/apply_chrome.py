#!/usr/bin/env python3
"""
apply_chrome.py — give every hand-written live page the same header, nav and footer.

Pages generated by build_content.py already use sitechrome; this script handles the
hand-written ones (root pages, en/, living/, personal/, business/, teacher legacy pages,
the India/Myanmar gallery pages). It replaces the <header class="header">…</header> and
<footer class="footer">…</footer> blocks, wraps the content in <main id="main">, adds the
skip link, fixes the <html> lang/dir attributes and the mobile-menu script.

Idempotent: running it twice changes nothing the second time.

Usage: python3 scripts/apply_chrome.py [--check] [paths...]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sitechrome as chrome  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# folder -> (active nav key, English equivalent section page)
SECTIONS = {
    "": ("home", None),
    "en": ("home", None),
    "living": ("archive", "living.html"),
    "personal": ("archive", "archive.html"),
    "business": ("archive", "archive.html"),
    "teachers": ("spiritual", "spiritual.html"),
    "travel": ("travel", "travel.html"),
}
ROOT_ACTIVE = {"index": "home", "spiritual": "spiritual", "travel": "travel", "archive": "archive",
               "living": "archive", "ethics": "archive", "admin": "home", "404": "home"}
# English-only description pages whose Hebrew counterpart is the original site itself
EN_ALT = {"living": "../living/index.html", "ethics": "../personal/ethics/index.html"}

HEADER_RE = re.compile(r"[ \t]*<header class=\"header\">.*?</header>\n?", re.S)
FOOTER_RE = re.compile(r"[ \t]*<footer class=\"footer\">.*?</footer>\n?", re.S)
NAV_SCRIPT_RE = re.compile(
    r"[ \t]*<script>\s*(?:\(function \(\) \{\s*var t = document\.querySelector\('\.nav__toggle'\);.*?\}\)\(\);|document\.querySelector\('\.nav__toggle'\)\.addEventListener\('click', function\(\) \{\s*"
    r"document\.querySelector\('\.nav__list'\)\.classList\.toggle\('is-open'\);\s*\}\);)\s*</script>\n?", re.S)
# the old inline menu handler embedded in a larger <script> (India/Myanmar/business pages): a second handler
# would toggle the menu back shut on every tap
OLD_HANDLER_RE = re.compile(
    r"[ \t]*// Mobile (?:menu|navigation toggle)\n[ \t]*document\.querySelector\('\.nav__toggle'\)\.addEventListener\('click', function\(\) \{\s*"
    r"document\.querySelector\('\.nav__list'\)\.classList\.toggle\('is-open'\);\s*\}\);\n(?:[ \t]*\n)?")
EMPTY_SCRIPT_RE = re.compile(r"[ \t]*<script>\s*</script>\n?")
SKIP_RE = re.compile(r"[ \t]*<a class=\"skip-link\" href=\"#main\">[^<]*</a>\n?")
MAIN_OPEN_RE = re.compile(r"[ \t]*<main id=\"main\"(?P<attrs>[^>]*)>\n?")
MAIN_CLOSE_RE = re.compile(r"[ \t]*</main>\n?")


def classify(path: Path):
    relp = path.relative_to(ROOT)
    parts = relp.parts
    lang = "en" if parts[0] == "en" else "he"
    depth = len(parts) - 1
    top = parts[0] if len(parts) > 1 else ""
    if top == "en":
        active = ROOT_ACTIVE.get(path.stem, "home")
        alt = EN_ALT.get(path.stem) or (f"../{path.stem}.html" if path.stem in ROOT_ACTIVE else None)
    elif top == "":
        active = ROOT_ACTIVE.get(path.stem, "home")
        alt = f"en/{path.stem}.html" if path.stem in ROOT_ACTIVE and path.stem not in ("admin", "404") else None
        if path.stem == "404":
            alt = "/en/index.html"
    else:
        active, en_page = SECTIONS.get(top, ("home", None))
        if top == "personal" and len(parts) > 2 and parts[1] == "ethics":
            en_page = "ethics.html"
        if path.name == "index.en.html":
            lang = "en"
            alt = "index.html"
        elif (path.parent / "index.en.html").exists() and path.name == "index.html":
            alt = "index.en.html"
        else:
            alt = ("../" * depth) + "en/" + en_page if en_page else None
    return lang, depth, active, alt


def apply(path: Path, check: bool = False) -> bool:
    text = path.read_text(encoding="utf-8")
    if "<header class=\"header\">" not in text or "<footer class=\"footer\">" not in text:
        # pages without the shared chrome (viewer.html) still get versioned asset links
        depth = len(path.relative_to(ROOT).parts) - 1
        new = version_assets(text, depth)
        if new == text:
            return False
        if not check:
            path.write_text(new, encoding="utf-8", newline="\n")
        return True
    lang, depth, active, alt = classify(path)
    new = text
    # <html> attributes
    new = re.sub(r"<html[^>]*>", f'<html lang="{lang}" dir="{"rtl" if lang == "he" else "ltr"}">', new, count=1)
    # chrome blocks
    new = HEADER_RE.sub(lambda m: chrome.header_html(lang, depth, active, alt) + "\n", new, count=1)
    new = FOOTER_RE.sub(lambda m: chrome.footer_html(lang, depth) + "\n", new, count=1)
    new = NAV_SCRIPT_RE.sub("", new)
    new = OLD_HANDLER_RE.sub("", new)
    new = EMPTY_SCRIPT_RE.sub("", new)
    # legacy photo pages: the shared lightbox (gallery.js) unless the page carries its own
    if 'class="gallery__item"' in new and "assets/js/gallery.js" not in new and 'id="lightbox"' not in new:
        new = new.replace("</body>", f'  <script src="{chrome.asset_url(depth, "assets/js/gallery.js")}"></script>\n</body>', 1)
    new = SKIP_RE.sub("", new)
    m_main = MAIN_OPEN_RE.search(new)
    main_attrs = m_main.group("attrs") if m_main else ""
    new = MAIN_OPEN_RE.sub("", new)
    new = MAIN_CLOSE_RE.sub("", new)
    # skip link before header, <main> around the content between header and footer
    new = new.replace("  <header class=\"header\">", f'  <a class="skip-link" href="#main">{chrome.SKIP_LABEL[lang]}</a>\n  <header class="header">', 1)
    new = new.replace("</header>\n", f"</header>\n\n  <main id=\"main\"{main_attrs}>\n", 1)
    new = new.replace("  <footer class=\"footer\">", "  </main>\n\n  <footer class=\"footer\">", 1)
    # nav script before </body>
    new = new.replace("</body>", chrome.NAV_SCRIPT + "\n</body>", 1)
    # drop the inline English font overrides (now in style.css) and stray Playfair font loads
    new = re.sub(r"\s*<style>\s*body \{ font-family: var\(--font-english\); direction: ltr; \}\s*h1, h2, h3, h4, h5, h6 \{ font-family: var\(--font-english\); \}\s*</style>", "", new)
    new = new.replace("&family=Playfair+Display:wght@400;600;700", "").replace(";600;700&", ";600&")
    # versioned asset references (style.css, assets/js/*.js) so browsers never use a stale cached copy
    new = version_assets(new, depth)
    # collapse runs of blank lines (keeps the script idempotent), trailing blank lines
    new = re.sub(r"\n{3,}", "\n\n", new)
    new = new.rstrip("\n") + "\n"
    if new == text:
        return False
    if not check:
        path.write_text(new, encoding="utf-8", newline="\n")
    return True


ASSET_RE = re.compile(r'((?:href|src)=")(?:\.\./)*(style\.css|assets/js/[A-Za-z0-9_-]+\.js)(?:\?v=[0-9a-f]+)?"')


def version_assets(text: str, depth: int) -> str:
    return ASSET_RE.sub(lambda m: m.group(1) + chrome.asset_url(depth, m.group(2)) + '"', text)


def default_targets() -> list[Path]:
    out: list[Path] = []
    for pattern in ("*.html", "en/*.html", "living/*.html", "living/Process/*.html", "living/Affluenza/*.html",
                    "personal/*.html", "personal/*/*.html", "personal/*/*/*.html", "business/*.html",
                    "teachers/*/*.html", "travel/india/*.html", "travel/myanmar/*.html", "travel/india/texts/*.html"):
        out += sorted(ROOT.glob(pattern))
    return [p for p in out if "old-site" not in p.parts]


def main(argv: list[str]) -> int:
    check = "--check" in argv
    paths = [Path(a).resolve() for a in argv if not a.startswith("--")] or default_targets()
    changed = 0
    for p in paths:
        if p.is_file() and apply(p, check):
            changed += 1
            print(("would update " if check else "updated ") + p.relative_to(ROOT).as_posix())
    print(f"{changed} page(s) {'need updating' if check else 'updated'}")
    return 1 if (check and changed) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
