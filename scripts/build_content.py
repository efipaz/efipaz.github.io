def build_inbox() -> None:
    """Files Efi dropped at the repo root by mistake are moved where the site expects them."""
    today = dt.date.today().isoformat()
    for p in sorted(ROOT.iterdir()):
        if not p.is_file() or p.name in ROOT_KEEP or p.name.startswith("."):
            continue
        ext = p.suffix.lower()
        if ext in (".pdf",) or ext in DOC_CONVERT_EXT:
            dest = ROOT / "books" / p.name
            msg = f"הקובץ '{p.name}' הועלה לתיקייה הראשית במקום ל-books/ — הועבר אוטומטית לספרים"
        elif ext in IMAGE_EXT or ext in HEIC_EXT or ext in VIDEO_EXT:
            if p.name.lower() in ("busconjpg",):
                continue
            dest = ROOT / "travel" / f"inbox-{today}" / p.name
            msg = f"התמונה '{p.name}' הועלתה לתיקייה הראשית — הועברה לגלריה travel/inbox-{today}"
        else:
            continue
        if dest.exists():
            report("warn", f"'{p.name}' בתיקייה הראשית כבר קיים ב-{rel(dest.parent)} — לא הועבר", rel(p))
            continue
        if DRY_RUN:
            report("ok", msg + " (dry-run)", rel(p))
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        p.rename(dest)
        CHANGED.append(rel(dest))
        if dest.parent.parent == ROOT / "travel" and not (dest.parent / "info.txt").exists():
            write_text(dest.parent / "info.txt", f"כותרת: תמונות חדשות ({today})\nתיאור: תמונות שהועלו לתיקייה הראשית. כדי להציג אותן באתר – למחוק את השורה 'מוסתר' ולתת שם.\nמוסתר: כן\n")
            msg += ". הגלריה מוסתרת עד שנותנים לה שם (לוח הבקרה ← לתקן טקסט)"
        report("ok", msg, rel(dest))


