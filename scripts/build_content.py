ALIAS_TO_KEY = {a: k for k, aliases in KEY_ALIASES.items() for a in aliases}
POSITIONAL = ["title", "description", "title_en", "description_en"]


def parse_info(text: str) -> dict:
    """
    Tolerant metadata parser for info.txt / sidecar .txt files.

    Supports `key: value` lines (Hebrew or English keys, see KEY_ALIASES), multi-line
    values (lines without a key continue the previous value), and a plain positional
    format: line 1 title, line 2 description, line 3 English title, line 4 English description.
    """
    info: dict[str, str] = {}
    lines = [ln.rstrip("\r") for ln in text.splitlines()]
    has_keys = any(re.match(r"^\s*[\w֐-׿ ]{1,30}\s*:", ln) and
                   re.split(r"\s*:", ln, maxsplit=1)[0].strip().lower() in ALIAS_TO_KEY for ln in lines)
    if not has_keys:
        vals = [ln.strip() for ln in lines if ln.strip()]
        # A short key-less file is "title / description". Anything longer is prose
        # (a transcript, notes), not metadata: ignore it rather than turn it into a title.
        if 0 < len(vals) <= 2 and all(len(v) <= 120 for v in vals):
            for key, val in zip(POSITIONAL[:2], vals):
                info[key] = val
        elif vals:
            info["_ignored"] = "1"
        return info
    current = None
    for ln in lines:
        m = re.match(r"^\s*([\w֐-׿ ]{1,30})\s*:\s*(.*)$", ln)
        if m and m.group(1).strip().lower() in ALIAS_TO_KEY:
            current = ALIAS_TO_KEY[m.group(1).strip().lower()]
            info[current] = m.group(2).strip()
        elif current:
            info[current] = (info[current] + "\n" + ln.strip()).strip()
        elif ln.strip():
            info.setdefault("bio", "")
            info["bio"] = (info["bio"] + "\n" + ln.strip()).strip()
            current = "bio"
    return info


def load_info(folder: Path, name: str = "info.txt") -> dict:
    p = folder / name
    if p.exists():
        try:
            info = parse_info(read_text_tolerant(p))
            if info.get("_ignored"):
                report("warn", f"הקובץ {rel(p)} נראה כטקסט חופשי ולא כקובץ פרטים (שורות 'שם: …' / 'כותרת: …'), ולכן לא השתמשתי בו", rel(p))
                return {}
            return info
        except Exception as e:  # noqa: BLE001
            report("warn", f"לא הצלחתי לקרוא את {rel(p)}: {e}", rel(p))
    pj = folder / "info.json"
    if pj.exists():
        try:
            data = json.loads(read_text_tolerant(pj))
            return {ALIAS_TO_KEY.get(str(k).lower(), str(k)): (v if isinstance(v, str) else json.dumps(v, ensure_ascii=False))
                    for k, v in data.items()}
        except Exception as e:  # noqa: BLE001
            report("error", f"הקובץ {rel(pj)} אינו JSON תקין ({e}). השתמשתי בשם התיקייה במקום.", rel(pj))
    return {}


def sidecar_info(file: Path) -> dict:
    """Metadata for a file from `<stem>.txt` next to it."""
    p = file.with_suffix(".txt")
    if p.exists() and p != file:
        try:
            info = parse_info(read_text_tolerant(p))
            if info.get("_ignored"):
                report("warn", f"הקובץ {rel(p)} נראה כטקסט חופשי ולא כקובץ כותרת (שורות 'כותרת: …' / 'תיאור: …'), ולכן לא השתמשתי בו", rel(p))
                return {}
            return info
        except Exception as e:  # noqa: BLE001
            report("warn", f"לא הצלחתי לקרוא את {rel(p)}: {e}", rel(p))
    return {}


def paragraphs(text: str) -> str:
    parts = [p.strip() for p in re.split(r"\n\s*\n|\n", text or "") if p.strip()]
    return "\n".join(f"<p>{esc(p)}</p>" for p in parts)


def first_paragraph(text: str) -> str:
    parts = [p.strip() for p in re.split(r"\n\s*\n|\n", text or "") if p.strip()]
    return parts[0] if parts else ""


def exif_datetime(p: Path) -> str | None:
    if Image is None:
        return None
    try:
        with Image.open(p) as im:
            ex = im.getexif()
            val = None
            try:
                val = ex.get_ifd(0x8769).get(36867)
            except Exception:  # noqa: BLE001
                pass
            val = val or ex.get(306)
            if val and re.match(r"\d{4}:\d{2}:\d{2}", str(val)):
                return str(val)[:10].replace(":", "-")
    except Exception:  # noqa: BLE001
        return None
    return None


# ----------------------------------------------------------------------------- injection

def inject(page: Path, key: str, html: str) -> bool:
    """Replace the block between <!-- auto:key --> and <!-- /auto:key --> in page."""
    if not page.exists():
        return False
    text = page.read_text(encoding="utf-8")
    start = f"<!-- auto:{key} -->"
    end = f"<!-- /auto:{key} -->"
    if start not in text or end not in text:
        report("error", f"בעמוד {rel(page)} חסר הסימן <!-- auto:{key} --> ולכן התוכן החדש לא הוכנס אליו (לתקן את העמוד)", rel(page))
        return False
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    new = f"{pre}{start}\n{html.rstrip()}\n{end}{post}"
    return write_text(page, new)


