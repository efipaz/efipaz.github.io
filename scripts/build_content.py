def log(msg: str) -> None:
    print(msg, flush=True)


def report(level: str, he: str, path: str = "") -> None:
    REPORT.append({"level": level, "he": he, "path": path})
    log(f"[{level}] {he}" + (f"  ({path})" if path else ""))


def rel(p: Path) -> str:
    return p.resolve().relative_to(ROOT).as_posix()


def url(p: Path | str) -> str:
    """Percent-encode a site-root-relative path once."""
    s = p if isinstance(p, str) else rel(p)
    return urllib.parse.quote(s, safe="/")


def write_text(p: Path, text: str) -> bool:
    """Write only if content changed. Returns True when the file was written."""
    if p.exists():
        try:
            if p.read_text(encoding="utf-8") == text:
                return False
        except UnicodeDecodeError:
            pass
    if DRY_RUN:
        log(f"  (dry-run) would write {rel(p)}")
        return True
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    CHANGED.append(rel(p))
    return True


def write_json(p: Path, data) -> bool:
    return write_text(p, json.dumps(data, ensure_ascii=False, indent=1) + "\n")


def read_text_tolerant(p: Path) -> str:
    raw = p.read_bytes()
    for enc in ("utf-8-sig", "utf-16"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("cp1255", errors="replace")


def file_sig(p: Path) -> str:
    """Stable content signature: path + size + md5 of the first 64 KiB."""
    h = hashlib.md5()
    h.update(rel(p).encode("utf-8"))
    h.update(str(p.stat().st_size).encode())
    with p.open("rb") as f:
        h.update(f.read(65536))
    return h.hexdigest()[:10]


def run(cmd: list[str], timeout: int = 180) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


def have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def clean_name(stem: str) -> str:
    """Folder/file name -> human title: collapse whitespace, strip underscores."""
    s = stem.replace("_", " ")
    s = re.sub(r"\s+", " ", s).strip()
    return s


