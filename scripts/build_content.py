def thumb_name(src: Path, base: Path) -> str:
    """Stable thumbnail file name: relative path (folders joined by __) + content signature."""
    relp = src.relative_to(base).as_posix()
    stem = re.sub(r"\.[A-Za-z0-9]+$", "", relp.replace("/", "__"))
    stem = re.sub(r"[^\w.-]+", "_", stem, flags=re.UNICODE)[:80]
    return f"{stem}.{file_sig(src)[:6]}.jpg"


def make_thumb(src: Path, dst: Path, max_px: int = THUMB_MAX) -> bool:
    """Create a JPEG thumbnail if missing. Returns True if written (git mtimes are meaningless,
    so the file name carries the content signature instead, see thumb_name())."""
    if dst.exists() and dst.stat().st_size > 0:
        return False
    if DRY_RUN:
        return True
    try:
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im)
            im.thumbnail((max_px, max_px), Image.LANCZOS)
            if im.mode not in ("RGB", "L"):
                im = im.convert("RGB")
            buf = io.BytesIO()
            im.save(buf, "JPEG", quality=THUMB_QUALITY, optimize=True, progressive=True)
        data = buf.getvalue()
        if dst.exists() and dst.read_bytes() == data:
            return False
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)
        CHANGED.append(rel(dst))
        return True
    except Exception as e:  # noqa: BLE001
        report("warn", f"לא הצלחתי ליצור תמונה מוקטנת ל-{rel(src)}: {e}", rel(src))
        return False


_READABLE: dict[Path, bool] = {}


def image_readable(p: Path) -> bool:
    """True if Pillow can decode the file. Some old 'jpg' files on the site are corrupt data."""
    if p in _READABLE:
        return _READABLE[p]
    ok = False
    try:
        with Image.open(p) as im:
            im.verify()
        ok = True
    except Exception:  # noqa: BLE001
        ok = False
    _READABLE[p] = ok
    return ok


def image_size(p: Path) -> tuple[int, int]:
    try:
        with Image.open(p) as im:
            im = ImageOps.exif_transpose(im)
            return im.size
    except Exception:  # noqa: BLE001
        return (0, 0)


def convert_heic(src: Path) -> Path | None:
    dst = src.with_suffix(".jpg")
    if dst.exists():
        return dst
    if DRY_RUN:
        return None
    if not have("convert"):
        report("warn", f"אין תמיכה ב-HEIC בסביבה הזו, {rel(src)} דולג", rel(src))
        return None
    r = run(["convert", str(src), "-auto-orient", "-quality", "92", str(dst)])
    if r.returncode == 0 and dst.exists():
        CHANGED.append(rel(dst))
        report("ok", f"התמונה {src.name} הומרה מ-HEIC ל-JPG", rel(dst))
        return dst
    report("warn", f"לא הצלחתי להמיר את {rel(src)} מ-HEIC: {r.stderr[:200]}", rel(src))
    return None


def video_poster(src: Path, dst: Path) -> bool:
    if dst.exists() and dst.stat().st_size > 0:
        return False
    if DRY_RUN or not have("ffmpeg"):
        return False
    r = run(["ffmpeg", "-y", "-loglevel", "error", "-ss", "1", "-i", str(src), "-frames:v", "1",
             "-vf", f"scale='min({THUMB_MAX},iw)':-2", "-q:v", "3", str(dst)], timeout=120)
    if r.returncode == 0 and dst.exists():
        CHANGED.append(rel(dst))
        return True
    return False


