def fetch_archive_org() -> list[dict] | None:
    q = urllib.parse.quote(f"uploader:({ARCHIVE_ORG_UPLOADER})")
    api = (f"https://archive.org/advancedsearch.php?q={q}&fl[]=identifier&fl[]=title&fl[]=mediatype"
           f"&fl[]=publicdate&fl[]=collection&fl[]=description&rows=500&output=json")
    try:
        with urllib.request.urlopen(api, timeout=30) as r:
            docs = json.load(r)["response"]["docs"]
    except Exception as e:  # noqa: BLE001
        report("warn", f"לא הצלחתי לקרוא את רשימת ההקלטות מ-archive.org ({e}); נשארה הרשימה הקודמת")
        return None
    items = []
    for d in docs:
        coll = d.get("collection") or []
        coll = [coll] if isinstance(coll, str) else coll
        if d.get("mediatype") not in ("audio", "movies") or "emptyfiles" in coll:
            continue
        if not archive_item_has_content(d["identifier"]):
            continue
        title = str(d.get("title", d["identifier"])).strip()
        m = re.search(r"(20\d\d|19\d\d)", title)
        items.append({
            "id": d["identifier"],
            "title": title,
            "mediatype": d.get("mediatype", ""),
            "year": m.group(1) if m else str(d.get("publicdate", ""))[:4],
            "url": f"https://archive.org/details/{d['identifier']}",
            "embed": f"https://archive.org/embed/{d['identifier']}",
        })
    items.sort(key=lambda i: (-int(i["year"] or 0), i["title"]))
    return items


def archive_item_has_content(identifier: str) -> bool:
    """True if the archive.org item has at least one real (non-metadata) file."""
    try:
        with urllib.request.urlopen(f"https://archive.org/metadata/{identifier}/files", timeout=30) as r:
            files = json.load(r).get("result", [])
    except Exception:  # noqa: BLE001
        return True  # be generous on a transient error
    skip = ("_meta.xml", "_files.xml", "_meta.sqlite", "_reviews.xml", "__ia_thumb.jpg", "_archive.torrent")
    return any(f.get("source") == "original" and not f["name"].endswith(skip) for f in files)


