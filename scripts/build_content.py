def build_sitemap() -> None:
    pages: list[tuple[str, str | None]] = []  # (path, alternate path)
    for name in ("", "spiritual.html", "travel.html", "archive.html"):
        pages.append((name, "en/" + name))
    # English descriptions of the Hebrew-only original sites
    pages.append(("living/index.html", "en/living.html"))
    pages.append(("personal/ethics/index.html", "en/ethics.html"))
    for folder in sorted(p for p in TRAVEL_DIR.iterdir() if p.is_dir()):
        if (folder / "index.html").exists() and MARKER in (folder / "index.html").read_text(encoding="utf-8", errors="replace"):
            pages.append((f"{rel(folder)}/", f"{rel(folder)}/index.en.html"))
        elif (folder / "index.html").exists() and (folder / "info.txt").exists():
            pages.append((f"{rel(folder)}/", None))
    for folder in sorted(p for p in TEACHERS_DIR.iterdir() if p.is_dir()):
        if (folder / "index.html").exists():
            pages.append((f"{rel(folder)}/", f"{rel(folder)}/index.en.html"))
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for path, alt in pages:
        for loc, other, lang, olang in ((path, alt, "he", "en"), (alt, path, "en", "he")):
            if loc is None:
                continue
            lines.append("  <url>")
            lines.append(f"    <loc>{esc(chrome.SITE_URL + '/' + url(loc))}</loc>")
            lines.append(f'    <xhtml:link rel="alternate" hreflang="{lang}" href="{esc(chrome.SITE_URL + "/" + url(loc))}"/>')
            if other is not None:
                lines.append(f'    <xhtml:link rel="alternate" hreflang="{olang}" href="{esc(chrome.SITE_URL + "/" + url(other))}"/>')
            lines.append("  </url>")
    lines.append("</urlset>")
    write_text(ROOT / "sitemap.xml", "\n".join(lines) + "\n")


