def convert_to_pdf(src: Path) -> Path | None:
    """doc/docx/odt/rtf/mht -> pdf next to the source (kept). Returns the pdf path or None."""
    dst = src.with_suffix(".pdf")
    if dst.exists():
        return dst
    if DRY_RUN:
        return None
    if not have("soffice"):
        report("warn", f"אין LibreOffice בסביבה הזו — {src.name} לא הומר ל-PDF", rel(src))
        return None
    env = dict(os.environ, HOME=str(ROOT / ".lo-home"))
    r = subprocess.run(["soffice", "--headless", "--norestore", "--convert-to", "pdf", "--outdir",
                        str(src.parent), str(src)], capture_output=True, text=True, timeout=300, env=env)
    shutil.rmtree(ROOT / ".lo-home", ignore_errors=True)
    if dst.exists():
        CHANGED.append(rel(dst))
        report("ok", f"הקובץ {src.name} הומר ל-PDF", rel(dst))
        return dst
    report("error", f"לא הצלחתי להמיר את {src.name} ל-PDF ({(r.stderr or r.stdout)[:200].strip()}). "
                    f"אפשר לשמור אותו כ-PDF מ-Word ולהעלות שוב.", rel(src))
    return None


def pdf_is_valid(pdf: Path) -> bool:
    if not have("pdfinfo"):
        return True
    try:
        return run(["pdfinfo", str(pdf)], timeout=60).returncode == 0
    except Exception:  # noqa: BLE001
        return True


def pdf_cover(pdf: Path, cover: Path) -> bool:
    if cover.exists():
        return False
    if DRY_RUN or not have("pdftoppm"):
        return False
    tmp = cover.with_name(cover.stem + "_tmp")
    r = run(["pdftoppm", "-jpeg", "-r", "60", "-f", "1", "-l", "1", "-scale-to", "600", str(pdf), str(tmp)])
    produced = sorted(cover.parent.glob(cover.stem + "_tmp*.jpg"))
    if r.returncode == 0 and produced:
        produced[0].replace(cover)
        for extra in produced[1:]:
            extra.unlink()
        CHANGED.append(rel(cover))
        return True
    for extra in produced:
        extra.unlink()
    report("warn", f"לא הצלחתי להפיק שער מהעמוד הראשון של {pdf.name}; הספר יוצג בלי שער", rel(pdf))
    return False


def scan_documents(folder: Path, covers_dir: Path) -> list[dict]:
    """Collect PDFs (converting other formats) in folder and one level of category subfolders."""
    items: list[dict] = []
    seen_stems: set[str] = set()
    previous_sources: dict[str, str] = {}
    mf = folder / "manifest.json"
    if mf.exists():
        try:
            previous_sources = {i["path"]: i.get("source_sig") for i in json.loads(mf.read_text(encoding="utf-8")).get("items", []) if i.get("source_sig")}
        except Exception:  # noqa: BLE001
            previous_sources = {}
    files = sorted(p for p in folder.rglob("*") if p.is_file() and covers_dir not in p.parents
                   and not p.name.startswith(".") and len(p.relative_to(folder).parts) <= 3)
    # PDFs first, so a converted PDF wins over its source
    files.sort(key=lambda p: (0 if p.suffix.lower() == ".pdf" else 1, p.as_posix()))
    for p in files:
        ext = p.suffix.lower()
        stem_key = p.with_suffix("").as_posix()
        if ext == ".pdf":
            pdf = p
        elif ext in DOC_CONVERT_EXT:
            if stem_key in seen_stems:
                # a PDF with this name already exists: reconvert only if the source changed
                prev = previous_sources.get(rel(p.with_suffix(".pdf")))
                if prev and prev != file_sig(p) and not DRY_RUN:
                    p.with_suffix(".pdf").unlink(missing_ok=True)
                    report("ok", f"הקובץ {p.name} הוחלף — ה-PDF נוצר מחדש", rel(p))
                    pdf = convert_to_pdf(p)
                    if pdf:
                        for it in items:
                            if it["path"] == rel(pdf):
                                it["source_sig"] = file_sig(p)
                                it["cover"] = None
                continue
            pdf = convert_to_pdf(p)
            if not pdf:
                continue
        else:
            continue  # txt sidecars, images, unsupported types are silently ignored here
        if stem_key in seen_stems:
            continue
        seen_stems.add(stem_key)
        if not pdf_is_valid(pdf):
            report("error", f"הקובץ {pdf.name} אינו PDF תקין ולא הוצג. אפשר לפתוח אותו במחשב, לשמור מחדש כ-PDF ולהעלות שוב.", rel(pdf))
            continue
        meta = sidecar_info(pdf)
        category = pdf.parent.relative_to(folder).parts[0] if pdf.parent != folder else ""
        sig = file_sig(pdf)
        cover = covers_dir / f"{sig}.jpg"
        pdf_cover(pdf, cover)
        source = next((pdf.with_suffix(e) for e in (".docx", ".doc", ".odt", ".rtf", ".mht", ".mhtml") if pdf.with_suffix(e).exists()), None)
        sidecar = pdf.with_suffix(".txt")
        items.append({
            "sidecar": rel(sidecar) if sidecar.exists() else None,
            "source_sig": file_sig(source) if source else None,
            "title": meta.get("title") or clean_name(pdf.stem),
            "title_en": meta.get("title_en") or "",
            "description": meta.get("description") or "",
            "description_en": meta.get("description_en") or "",
            "path": rel(pdf),
            "size_kb": round(pdf.stat().st_size / 1024),
            "category": clean_name(category),
            "cover": rel(cover) if cover.exists() else None,
            "order": meta.get("order") or "",
        })
    for it in items:
        if it["cover"] is None and not DRY_RUN:
            pdf = ROOT / it["path"]
            if pdf.exists():
                cover = covers_dir / f"{file_sig(pdf)}.jpg"
                pdf_cover(pdf, cover)
                it["cover"] = rel(cover) if cover.exists() else None
    # orphan covers
    used = {Path(i["cover"]).name for i in items if i["cover"]}
    if covers_dir.exists():
        for c in covers_dir.iterdir():
            if c.is_file() and c.name not in used and c.suffix.lower() in (".jpg", ".png"):
                if DRY_RUN:
                    continue
                c.unlink()
                CHANGED.append(rel(c))
    def sort_key(i):
        o = i["order"]
        return (0 if o else 1, float(o) if re.match(r"^-?\d+(\.\d+)?$", o or "") else 0, i["title"])
    items.sort(key=sort_key)
    return items


