#!/usr/bin/env python3
"""
build_content.py — the content engine of efipaz.com.

Efi uploads files through the GitHub web UI; this script turns them into site content.
It runs in GitHub Actions (.github/workflows/auto-process-content.yml) and locally.

Principles
  * Forgiving: a bad file never stops the build. It is listed in the report and skipped.
  * Idempotent: running twice changes nothing the second time.
  * Static: content is injected into the HTML pages between markers, so the site
    works without JavaScript and the English pages get English text.

What it does
  books/ and transcripts/   PDF cover from page 1, doc/docx/odt/rtf/mht -> PDF via LibreOffice,
                            optional <name>.txt sidecar (title / description / title_en / description_en)
  travel/<folder>/          any folder with photos or videos becomes a gallery:
                            thumbnails, HEIC -> JPG, video posters, index.html + index.en.html,
                            optional info.txt (title / description / ...). A folder with only
                            cover.* is a "coming soon" card.
  teachers/<id>/            info.txt (or info.json) + portrait + files -> index.html + index.en.html
  recordings                archive.org items uploaded by Efi -> recordings/manifest.json
  root inbox                media/documents dropped at the repo root are moved to the right folder
  report                    content-report.md (Hebrew, for Efi) + assets/data/content-report.json

Usage
  python3 scripts/build_content.py [--dry-run] [--no-network] [--only books,galleries,teachers,recordings,inbox]
"""
